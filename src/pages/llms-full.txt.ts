// /llms-full.txt : tout le contenu (anglais) en texte brut pour les assistants IA (complément de /llms.txt).
import type { APIRoute } from 'astro';
import { site, abs, addressLine } from '../lib/site';
import { eventTypes } from '../lib/events';
import { reviews, googleRating } from '../lib/reviews';
import { feest } from '../lib/feestdagen';
import { ui } from '../i18n/ui';
import { pagePath, eventPath } from '../i18n/routes';

export const GET: APIRoute = () => {
  const s = ui.en;
  const parts = [
    `# ${site.name} — full content`,
    '',
    `> ${s.meta.homeDesc}`,
    '',
    `Atelier: ${addressLine}, Belgium. Phone: ${site.contacts.map((c) => `${c.name} ${c.phone}`).join(', ')}. Email: ${site.email}. Instagram: ${site.social.instagram.url}`,
    '',
    '---',
    '',
    '## About Bert & Aude',
    '',
    `- URL: ${abs(pagePath('about', 'en'))}`,
    '',
    ...s.about.story.flatMap((p) => [p, '']),
    `### ${s.about.bertTitle}`,
    '',
    s.about.bert,
    '',
    `### ${s.about.audeTitle}`,
    '',
    s.about.aude,
    '',
    '---',
    '',
    '## Catering',
    '',
    `- URL: ${abs(pagePath('catering', 'en'))}`,
    '',
    s.catering.lead,
    '',
    '### What’s included',
    '',
    ...s.catering.included.map((i) => `- **${i.title}**: ${i.text}`),
    '',
    ...eventTypes.flatMap((e) => {
      const c = e.copy.en;
      return [
        `### ${c.name}`,
        '',
        `- URL: ${abs(eventPath(e.key, 'en'))}`,
        '',
        c.lead,
        '',
        ...c.body.flatMap((p) => [p, '']),
        ...c.ideas.map((i) => `- **${i.title}**: ${i.text}`),
        '',
        ...c.faq.flatMap((f) => [`**${f.q}** ${f.a}`, '']),
      ];
    }),
    '### FAQ',
    '',
    ...s.catering.faq.flatMap((f) => [`**${f.q}** ${f.a}`, '']),
    '---',
    '',
    '## The atelier (private dining)',
    '',
    `- URL: ${abs(pagePath('atelier', 'en'))}`,
    '',
    s.atelier.lead,
    '',
    ...s.atelier.intro.flatMap((p) => [p, '']),
    ...s.atelier.faq.flatMap((f) => [`**${f.q}** ${f.a}`, '']),
    '---',
    '',
    '## Takeaway',
    '',
    `- URL: ${abs(pagePath('takeaway', 'en'))}`,
    '',
    s.takeaway.lead,
    '',
    ...s.takeaway.how.map((h, i) => `${i + 1}. **${h.title}**: ${h.text}`),
    '',
    `### ${feest.en.label}`,
    '',
    feest.en.lead,
    '',
    `**${feest.en.menuTitle}**`,
    ...feest.en.courses.map((c) => `- ${c.name}: ${c.dish}`),
    ...feest.en.prices.map((p) => `- ${p.name}: ${p.price}`),
    feest.en.fourNote,
    '',
    `**${feest.en.classicsTitle}**`,
    ...feest.en.classics.map((c) => `- ${c.name}${c.note ? ` (${c.note})` : ''}: ${c.price}`),
    '',
    `**${feest.en.orderTitle}** (by email to afhaal@beau-moments.be): ${feest.en.order.join('; ')}`,
    `**${feest.en.pickupTitle}**: ${feest.en.pickup.join('; ')}`,
    '',
    '---',
    '',
    `## Google reviews (${googleRating.score}/5, ${googleRating.count} reviews; Dutch, original wording)`,
    '',
    ...reviews.map((r) => `- ${r.author} (${r.stars}/5): ${r.quote.nl}`),
    '',
  ];
  return new Response(parts.join('\n'), { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
};
